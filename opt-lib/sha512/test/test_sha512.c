static int check_case(const SHA512_BYTE *data, size_t len,
                      const SHA512_BYTE expected[64], size_t chunk,
                      size_t split, size_t output_offset) {
    SHA512_CTX ctx;
    _Alignas(8) SHA512_BYTE storage[80];
    SHA512_BYTE *hash = storage + 8 + output_offset;
    memset(&ctx, 0xa5, sizeof(ctx));
    memset(storage, 0xa5, sizeof(storage));
    sha512_init(&ctx);
    sha512_update(&ctx, NULL, 0);
    if (split <= len) {
        sha512_update(&ctx, data, split);
        sha512_update(&ctx, NULL, 0);
        sha512_update(&ctx, data + split, len - split);
    } else {
        size_t pos = 0;
        while (pos < len) {
            size_t size = len - pos;
            if (chunk && size > chunk) size = chunk;
            sha512_update(&ctx, data + pos, size);
            sha512_update(&ctx, data + pos, 0);
            pos += size;
        }
    }
    sha512_update(&ctx, NULL, 0);
    sha512_final(&ctx, hash);
    if (memcmp(hash, expected, 64) != 0) {
        fprintf(stderr,
                "SHA512 mismatch: len=%zu input_offset=%zu output_offset=%zu "
                "chunk=%zu split=%zu\n",
                len, (size_t)((uintptr_t)data & 7), output_offset, chunk,
                split);
        return 1;
    }
    for (size_t i = 0; i < sizeof(storage); ++i) {
        if (i >= 8 + output_offset && i < 72 + output_offset) continue;
        if (storage[i] != 0xa5) {
            fprintf(stderr, "SHA512 wrote outside the digest buffer\n");
            return 1;
        }
    }
    return 0;
}

int main(void) {
    static const size_t chunks[] = {1, 7, 31, 127, 128, 129, 257};
    static const size_t splits[] = {0, 1, 63, 111, 112, 127, 128, 129, 255};
    _Alignas(8) SHA512_BYTE storage[4096 + 7];
    size_t checks = 0;
    for (size_t v = 0; v < sizeof(vectors) / sizeof(vectors[0]); ++v) {
        size_t len = vectors[v].len;
        for (size_t input_offset = 0; input_offset < 8; ++input_offset) {
            SHA512_BYTE *data = storage + input_offset;
            for (size_t i = 0; i < len; ++i)
                data[i] = (SHA512_BYTE)(i * 131 + (i >> 3) * 17 + len * 29);
            // Exercise every combination of input and output alignment.
            for (size_t output_offset = 0; output_offset < 8; ++output_offset) {
                if (check_case(data, len, vectors[v].hash, 0, SIZE_MAX,
                               output_offset))
                    return 1;
                ++checks;
            }
            // Repeated short updates exercise partial and complete blocks.
            for (size_t c = 0; c < sizeof(chunks) / sizeof(chunks[0]); ++c) {
                if (check_case(data, len, vectors[v].hash, chunks[c], SIZE_MAX,
                               (input_offset + c) % 8))
                    return 1;
                ++checks;
            }
            // Follow a partial update with enough input to cross block edges.
            for (size_t s = 0; s < sizeof(splits) / sizeof(splits[0]); ++s) {
                if (splits[s] > len) continue;
                if (check_case(data, len, vectors[v].hash, 0, splits[s],
                               (input_offset + s) % 8))
                    return 1;
                ++checks;
            }
        }
    }
    printf("Passed %zu SHA512 regression cases\n", checks);
    return 0;
}
