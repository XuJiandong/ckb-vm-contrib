typedef void (*init_fn)(FIPS202_UINT64*);
typedef void (*absorb_fn)(FIPS202_UINT64*, const FIPS202_UINT8*,
                          FIPS202_SIZE_T);
typedef void (*squeeze_fn)(FIPS202_UINT8*, FIPS202_SIZE_T, FIPS202_UINT64*);
static const init_fn initializers[] = {shake128_inc_init, shake256_inc_init,
                                       sha3_256_inc_init, sha3_512_inc_init};
static const absorb_fn absorbers[] = {shake128_inc_absorb, shake256_inc_absorb,
                                      sha3_256_inc_absorb, sha3_512_inc_absorb};
static const squeeze_fn squeezers[] = {shake128_inc_squeeze,
                                       shake256_inc_squeeze};
static const FIPS202_SIZE_T rates[] = {168, 136, 136, 72};

static void hash_once(unsigned algorithm, FIPS202_UINT8* output,
                      FIPS202_SIZE_T outlen, const FIPS202_UINT8* input,
                      FIPS202_SIZE_T inlen) {
    switch (algorithm) {
        case 0:
            shake128(output, outlen, input, inlen);
            break;
        case 1:
            shake256(output, outlen, input, inlen);
            break;
        case 2:
            sha3_256(output, input, inlen);
            break;
        case 3:
            sha3_512(output, input, inlen);
            break;
    }
}

static void hash_incremental(unsigned algorithm, FIPS202_UINT8* output,
                             FIPS202_SIZE_T outlen, const FIPS202_UINT8* input,
                             FIPS202_SIZE_T inlen, FIPS202_SIZE_T chunk,
                             FIPS202_SIZE_T output_chunk) {
    FIPS202_UINT64 state[26];
    memset(state, 0xa5, sizeof(state));
    initializers[algorithm](state);
    absorbers[algorithm](state, NULL, 0);
    while (inlen) {
        FIPS202_SIZE_T take = inlen < chunk ? inlen : chunk;
        absorbers[algorithm](state, input, take);
        absorbers[algorithm](state, NULL, 0);
        input += take;
        inlen -= take;
    }
    switch (algorithm) {
        case 0:
            shake128_inc_finalize(state);
            break;
        case 1:
            shake256_inc_finalize(state);
            break;
        case 2:
            sha3_256_inc_finalize(output, state);
            return;
        case 3:
            sha3_512_inc_finalize(output, state);
            return;
    }
    squeezers[algorithm](NULL, 0, state);
    while (outlen) {
        FIPS202_SIZE_T take = outlen < output_chunk ? outlen : output_chunk;
        squeezers[algorithm](output, take, state);
        squeezers[algorithm](NULL, 0, state);
        output += take;
        outlen -= take;
    }
}

static int check_case(FIPS202_SIZE_T v, const FIPS202_UINT8* input,
                      FIPS202_SIZE_T input_offset, FIPS202_SIZE_T output_offset,
                      FIPS202_SIZE_T chunk, FIPS202_SIZE_T output_chunk,
                      int blocks) {
    _Alignas(8) FIPS202_UINT8 storage[360];
    FIPS202_UINT8* output = storage + 8 + output_offset;
    FIPS202_SIZE_T outlen = vectors[v].outlen;
    unsigned algorithm = vectors[v].algorithm;
    memset(storage, 0xa5, sizeof(storage));
    if (blocks) {
        FIPS202_UINT64 state[25];
        if (algorithm == 0) {
            shake128_absorb(state, input, vectors[v].len);
            shake128_squeezeblocks(output, 1, state);
            shake128_squeezeblocks(output + rates[algorithm], 1, state);
        } else {
            shake256_absorb(state, input, vectors[v].len);
            shake256_squeezeblocks(output, 1, state);
            shake256_squeezeblocks(output + rates[algorithm], 1, state);
        }
        outlen = 2 * rates[algorithm];
    } else if (chunk) {
        hash_incremental(algorithm, output, outlen, input, vectors[v].len,
                         chunk, output_chunk);
    } else {
        hash_once(algorithm, output, outlen, input, vectors[v].len);
    }
    if (memcmp(output, vectors[v].expected, outlen)) {
        fprintf(stderr,
                "FIPS202 mismatch: algorithm=%u len=%zu input=%zu "
                "output=%zu chunk=%zu squeeze=%zu blocks=%d\n",
                algorithm, vectors[v].len, input_offset, output_offset, chunk,
                output_chunk, blocks);
        return 1;
    }
    for (FIPS202_SIZE_T i = 0; i < sizeof(storage); ++i) {
        if (i >= 8 + output_offset && i < 8 + output_offset + outlen) continue;
        if (storage[i] != 0xa5) {
            fprintf(stderr, "FIPS202 wrote outside the output buffer\n");
            return 1;
        }
    }
    return 0;
}

int main(void) {
    _Alignas(8) FIPS202_UINT8 storage[1024 + 7];
    FIPS202_SIZE_T checks = 0;
    for (FIPS202_SIZE_T v = 0; v < sizeof(vectors) / sizeof(vectors[0]); ++v) {
        FIPS202_SIZE_T len = vectors[v].len;
        FIPS202_SIZE_T rate = rates[vectors[v].algorithm];
        FIPS202_SIZE_T chunks[] = {1, 7, 40, rate - 1};
        FIPS202_SIZE_T output_chunks[] = {7, rate - 1, rate + 1, 1};
        for (FIPS202_SIZE_T input_offset = 0; input_offset < 8;
             ++input_offset) {
            FIPS202_UINT8* input = storage + input_offset;
            for (FIPS202_SIZE_T i = 0; i < len; ++i)
                input[i] = (FIPS202_UINT8)(i * 131 + (i >> 3) * 17 + len * 29);
            for (FIPS202_SIZE_T output_offset = 0; output_offset < 8;
                 ++output_offset) {
                if (check_case(v, input, input_offset, output_offset, 0, 0, 0))
                    return 1;
                ++checks;
            }
            for (FIPS202_SIZE_T c = 0; c < sizeof(chunks) / sizeof(chunks[0]);
                 ++c) {
                if (check_case(v, input, input_offset, (input_offset + c) % 8,
                               chunks[c], output_chunks[c], 0))
                    return 1;
                ++checks;
            }
            if (vectors[v].algorithm < 2) {
                if (check_case(v, input, input_offset, input_offset, 0, 0, 1))
                    return 1;
                ++checks;
            }
            // SHA3 finalization allows the digest to overlap the public state.
            if (vectors[v].algorithm >= 2 && input_offset < 2) {
                FIPS202_UINT64 state[26];
                FIPS202_UINT8* output = (FIPS202_UINT8*)state + input_offset;
                unsigned algorithm = vectors[v].algorithm;
                initializers[algorithm](state);
                absorbers[algorithm](state, input, len);
                if (algorithm == 2)
                    sha3_256_inc_finalize(output, state);
                else
                    sha3_512_inc_finalize(output, state);
                if (memcmp(output, vectors[v].expected, vectors[v].outlen)) {
                    fprintf(stderr, "SHA3 overlapping finalization mismatch\n");
                    return 1;
                }
                ++checks;
            }
        }
    }
    printf("Passed %zu FIPS202 regression cases\n", checks);
    return 0;
}
